import { rename, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { LOCAL_DOCKER_NETWORK } from './local-docker-network.mjs'
import { runPnpmSync } from './run-pnpm.mjs'

const outputPath = resolve('src/lib/supabase/database.types.ts')
const temporaryPath = resolve(dirname(outputPath), '.database.types.ts.tmp')

const result = runPnpmSync(
  [
    'exec',
    'supabase',
    'gen',
    'types',
    'typescript',
    '--local',
    '--schema',
    'public',
    '--network-id',
    LOCAL_DOCKER_NETWORK,
  ],
  {
    encoding: 'utf8',
  },
)

if (result.error) {
  throw result.error
}

if (result.status !== 0) {
  process.stderr.write(result.stderr)
  process.exit(result.status ?? 1)
}

if (!result.stdout.includes('export type Database')) {
  throw new Error(
    'Supabase type generation did not return the expected Database type',
  )
}

try {
  await writeFile(
    temporaryPath,
    `// Generated by \`pnpm db:types\`. Do not edit manually.\n${result.stdout}`,
    'utf8',
  )
  await rename(temporaryPath, outputPath)
} finally {
  await rm(temporaryPath, { force: true })
}

process.stdout.write(`Generated ${outputPath}\n`)
